import os
import re
import subprocess
import sys
from concurrent.futures import ThreadPoolExecutor
from pathlib import Path

from pydantic import BaseModel
from pydantic_settings import CliApp, CliSubCommand

from knee_abnormality.cli import CLISettings, command, describe

ROOT = Path(__file__).resolve().parents[2]
SCRIPTS = ROOT / "scripts"
GENERATED = {
    "pipeline": (
        "Pipeline",
        (
            "The maintained prepare, train, predict, export and submit path. The bundle "
            "notebook template `inference.ipynb` is read by `export.py`."
        ),
    ),
    "tools": (
        "Tools",
        (
            "Maintained supporting commands. Every tool imports and runs against the "
            "current code."
        ),
    ),
}
LINK = re.compile(r"\]\(([^)#\s]+)")


def scripts(role: str) -> list[Path]:
    return sorted(
        path
        for path in (SCRIPTS / role).rglob("*.py")
        if "__pycache__" not in path.parts
        and not (path.name == "__init__.py" and not path.read_text().strip())
    )


def summary(path: Path) -> str:
    module = ".".join(path.relative_to(ROOT).with_suffix("").parts)
    result = subprocess.run(
        [sys.executable, "-m", module, "--help"],
        cwd=ROOT,
        capture_output=True,
        text=True,
        env=os.environ | {"CUDA_VISIBLE_DEVICES": ""},
        check=True,
    )
    lines = result.stdout[result.stdout.index("usage:") :].splitlines()
    usage_end = lines.index("")
    commands = re.search(r"\{([\w,-]+)\}\s+\.\.\.", " ".join(lines[:usage_end]))
    text = []
    for line in lines[usage_end + 1 :]:
        if not line.strip() or line.endswith(":"):
            break
        text.append(line.strip())
    if not text:
        raise ValueError(f"{module} has no CLI description")
    described = " ".join(text)
    if commands:
        described += f" (subcommands: {commands.group(1).replace(',', ', ')})"
    return described


def generated(role: str) -> str:
    title, preface = GENERATED[role]
    paths = scripts(role)
    with ThreadPoolExecutor(8) as pool:
        summaries = list(pool.map(summary, paths))
    rows = "".join(
        f"| [{path.name}]({path.name}) | {text} |\n"
        for path, text in zip(paths, summaries, strict=True)
    )
    return (
        f"# {title}\n\n{preface} Run a script with `--help` for its options, and "
        "search `docs/` for its path to find procedures and findings.\n\n"
        "Generated by `python -m scripts.tools.script_index write`; change the "
        "scripts' CLI descriptions, not this file.\n\n"
        f"| Script | Purpose |\n|---|---|\n{rows}"
    )


def unlisted_adhoc() -> list[str]:
    index = SCRIPTS / "adhoc" / "INDEX.md"
    linked = {
        (index.parent / link).resolve() for link in LINK.findall(index.read_text())
    }
    return [
        str(path.relative_to(ROOT))
        for path in scripts("adhoc")
        if not ({path, *path.parents} & linked)
    ]


def broken_links() -> list[str]:
    return [
        f"{index.relative_to(ROOT)}: {link}"
        for index in [SCRIPTS / "INDEX.md", *SCRIPTS.glob("*/INDEX.md")]
        for link in LINK.findall(index.read_text())
        if "://" not in link and not (index.parent / link).exists()
    ]


class Write(BaseModel):
    model_config = describe("Regenerate the pipeline and tools indexes")

    def cli_cmd(self) -> None:
        for role in GENERATED:
            (SCRIPTS / role / "INDEX.md").write_text(generated(role))


class Check(BaseModel):
    model_config = describe(
        "Check that the generated indexes are current, every adhoc script is listed "
        "and every index link resolves"
    )

    def cli_cmd(self) -> None:
        errors = [
            f"scripts/{role}/INDEX.md is stale; run write"
            for role in GENERATED
            if (SCRIPTS / role / "INDEX.md").read_text() != generated(role)
        ]
        errors += [f"Unlisted adhoc script: {path}" for path in unlisted_adhoc()]
        errors += [f"Broken link: {link}" for link in broken_links()]
        if errors:
            raise SystemExit("\n".join(errors))


class ScriptIndexCLI(CLISettings):
    model_config = describe(
        "Generate the pipeline and tools script indexes from each script's CLI "
        "description and check all script indexes"
    )

    write: CliSubCommand[Write] = command(Write)
    check: CliSubCommand[Check] = command(Check)

    def cli_cmd(self) -> None:
        CliApp.run_subcommand(self)


def main() -> None:
    CliApp.run(ScriptIndexCLI)


if __name__ == "__main__":
    main()
